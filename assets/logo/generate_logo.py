#!/usr/bin/env python3
"""
Xmana logo system generator.

Single source of truth for the Xmana wordmark geometry. It emits:
  * assets/logo/*.svg                          (vector masters, black background)
  * src/Xmana.App/Branding/Wordmarks.xaml      (vector DataTemplates used by the UI)
  * src/Xmana.App/Assets/*.png                 (package/tile/splash assets, rendered from vectors)

The wordmark is drawn from geometry (monoline strokes + one filled X), not from a
font, so it is original, font-independent and scales without raster enlargement.

Usage:  python3 assets/logo/generate_logo.py
Needs:  node + the `sharp` npm package (only for the PNG step; SVG/XAML need nothing).
"""
import json, math, os, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
APP_ASSETS = os.path.join(ROOT, "src", "Xmana.App", "Assets")
BRANDING_XAML = os.path.join(ROOT, "src", "Xmana.App", "Branding", "Wordmarks.xaml")

CAP, BASE, XH = 0.0, 70.0, 20.0      # cap top, baseline, x-height top (y grows downward)
K = 0.5523                            # quarter-ellipse bezier constant
FG, BG = "#EBEBEB", "#000000"         # near-white on solid black


def f(v):
    return f"{v:.2f}".rstrip("0").rstrip(".")


def solve_x_hw(width, sw, h=BASE):
    hw = sw
    for _ in range(60):
        hw = sw * math.sqrt(1 + ((width - hw) / h) ** 2)
    return hw


def build(variant):
    """Return dict(width, height, sw, shapes) for 'full' | 'compact' | 'icon'."""
    sw, gap, xw = {"full": (8.0, 11.0, 54.0), "compact": (10.5, 8.0, 54.0), "icon": (8.0, 0.0, 54.0)}[variant]
    hw = solve_x_hw(xw, sw)
    shapes, cur = [], 0.0

    # X: two flush parallelograms (horizontal cuts at cap line and baseline)
    shapes.append(("poly", [(cur, CAP), (cur + hw, CAP), (cur + xw, BASE), (cur + xw - hw, BASE)]))
    shapes.append(("poly", [(cur + xw - hw, CAP), (cur + xw, CAP), (cur + hw, BASE), (cur, BASE)]))
    cur += xw
    if variant == "icon":
        return dict(width=cur, height=BASE, sw=sw, shapes=shapes)

    rc = (50.0 - sw) / 2.0            # bowl centre-line radius -> outer extents 20..70
    wn = 2 * rc                        # n / a centre-line width
    wa = wn * 0.74                     # m arch width
    t = XH + sw / 2.0                  # arch top centre-line
    ry = 44.0 - t

    def arch(x0, w):
        return (f"M{f(x0)},44 C{f(x0)},{f(44 - K * ry)} {f(x0 + w / 2 - K * w / 2)},{f(t)} {f(x0 + w / 2)},{f(t)} "
                f"C{f(x0 + w / 2 + K * w / 2)},{f(t)} {f(x0 + w)},{f(44 - K * ry)} {f(x0 + w)},44 L{f(x0 + w)},{f(BASE)}")

    def letter_m(ox):
        d = f"M{f(ox)},{f(XH)} L{f(ox)},{f(BASE)} " + arch(ox, wa) + " " + arch(ox + wa, wa)
        return d, 2 * wa

    def letter_n(ox):
        return f"M{f(ox)},{f(XH)} L{f(ox)},{f(BASE)} " + arch(ox, wn), wn

    def letter_a(ox):
        cx, cy = ox + rc, 45.0
        d = (f"M{f(cx + rc)},{f(cy)} A{f(rc)},{f(rc)} 0 1 1 {f(cx - rc)},{f(cy)} "
             f"A{f(rc)},{f(rc)} 0 1 1 {f(cx + rc)},{f(cy)} M{f(cx + rc)},{f(XH)} L{f(cx + rc)},{f(BASE)}")
        return d, wn

    cur += gap - 2.0                   # X -> m: diagonals already leave optical space
    for i, fn in enumerate((letter_m, letter_a, letter_n, letter_a)):
        ox = cur + sw / 2.0
        d, w = fn(ox)
        shapes.append(("path", d))
        cur = ox + w + sw / 2.0
        if i < 3:
            cur += gap
    return dict(width=cur, height=BASE, sw=sw, shapes=shapes)


def svg_shapes(g, fill=FG):
    out = []
    for s in g["shapes"]:
        if s[0] == "poly":
            pts = " ".join(f"{f(x)},{f(y)}" for x, y in s[1])
            out.append(f'<polygon points="{pts}" fill="{fill}"/>')
        else:
            out.append(f'<path d="{s[1]}" fill="none" stroke="{fill}" stroke-width="{f(g["sw"])}" '
                       f'stroke-linecap="butt" stroke-linejoin="miter"/>')
    return "\n    ".join(out)


def svg_canvas(variant, cw, ch, mark_w_frac=None, mark_h_frac=None):
    g = build(variant)
    scale = (cw * mark_w_frac / g["width"]) if mark_w_frac else (ch * mark_h_frac / g["height"])
    tx = (cw - g["width"] * scale) / 2
    ty = (ch - g["height"] * scale) / 2
    return (f'<svg xmlns="http://www.w3.org/2000/svg" width="{cw}" height="{ch}" viewBox="0 0 {cw} {ch}">\n'
            f'  <rect width="{cw}" height="{ch}" fill="{BG}"/>\n'
            f'  <g transform="translate({f(tx)} {f(ty)}) scale({f(scale)})">\n    {svg_shapes(g)}\n  </g>\n</svg>\n')


def xaml_templates():
    lines = ['<?xml version="1.0" encoding="utf-8"?>',
             '<!-- GENERATED by assets/logo/generate_logo.py - do not edit by hand. -->',
             '<ResourceDictionary',
             '    xmlns="http://schemas.microsoft.com/winfx/2006/xaml/presentation"',
             '    xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml">']
    for name, variant in (("XmanaWordmarkFull", "full"), ("XmanaWordmarkCompact", "compact"), ("XmanaWordmarkIcon", "icon")):
        g = build(variant)
        lines += [f'  <DataTemplate x:Key="{name}">',
                  f'    <Viewbox Stretch="Uniform">',
                  f'      <Canvas Width="{f(g["width"])}" Height="{f(g["height"])}">']
        for s in g["shapes"]:
            if s[0] == "poly":
                pts = " ".join(f"{f(x)},{f(y)}" for x, y in s[1])
                lines.append(f'        <Polygon Points="{pts}" Fill="{{ThemeResource XmanaLogoBrush}}"/>')
            else:
                lines.append(f'        <Path Data="{s[1]}" Stroke="{{ThemeResource XmanaLogoBrush}}" StrokeThickness="{f(g["sw"])}"/>')
        lines += ['      </Canvas>', '    </Viewbox>', '  </DataTemplate>']
    lines.append('</ResourceDictionary>')
    return "\n".join(lines) + "\n"


# (file base name, width, height, variant, width fraction, height fraction)
ASSETS = [
    ("Square44x44Logo", 44, 44, "icon", None, 0.50),
    ("Square71x71Logo", 71, 71, "icon", None, 0.46),
    ("Square150x150Logo", 150, 150, "compact", 0.70, None),
    ("Wide310x150Logo", 310, 150, "full", 0.46, None),
    ("Square310x310Logo", 310, 310, "compact", 0.66, None),
    ("SplashScreen", 620, 300, "full", 0.46, None),
    ("StoreLogo", 50, 50, "icon", None, 0.50),
]
SCALES = (100, 200, 400)


def main():
    os.makedirs(APP_ASSETS, exist_ok=True)
    with open(os.path.join(HERE, "xmana-wordmark.svg"), "w") as fh:
        fh.write(svg_canvas("full", 1920, 1080, mark_w_frac=0.30))
    with open(os.path.join(HERE, "xmana-wordmark-compact.svg"), "w") as fh:
        fh.write(svg_canvas("compact", 960, 320, mark_w_frac=0.60))
    with open(os.path.join(HERE, "xmana-icon.svg"), "w") as fh:
        fh.write(svg_canvas("icon", 512, 512, mark_h_frac=0.50))
    with open(BRANDING_XAML, "w", encoding="utf-8") as fh:
        fh.write(xaml_templates())

    jobs = []
    for base, w, h, variant, wf, hf in ASSETS:
        for sc in SCALES:
            cw, ch = w * sc // 100, h * sc // 100
            svg = svg_canvas(variant, cw, ch, wf, hf)
            svg_path = os.path.join("/tmp", f"xmana_{base}_{sc}.svg")
            with open(svg_path, "w") as fh:
                fh.write(svg)
            jobs.append({"svg": svg_path, "png": os.path.join(APP_ASSETS, f"{base}.scale-{sc}.png"), "w": cw, "h": ch})
    jobs.append({"svg": os.path.join(HERE, "xmana-wordmark.svg"), "png": os.path.join(HERE, "xmana-wordmark-1920x1080.png"), "w": 1920, "h": 1080})
    job_file = "/tmp/xmana_render_jobs.json"
    with open(job_file, "w") as fh:
        json.dump(jobs, fh)

    env = dict(os.environ)
    if "NODE_PATH" not in env:
        try:
            env["NODE_PATH"] = subprocess.check_output(["npm", "root", "-g"], text=True).strip()
        except Exception:
            pass
    subprocess.check_call(["node", os.path.join(HERE, "render_pngs.mjs"), job_file], env=env)
    print("Generated", len(jobs), "PNG files")


if __name__ == "__main__":
    sys.exit(main())
